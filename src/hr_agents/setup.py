"""First-run configuration: render the operator's `.env` file.

Kept separate from the API and from `starters.py` because these values must exist
before the server starts. The CLI at `scripts/setup.py` prompts for the handful a
fresh install needs, generates the admin key, and writes the file; nothing here
talks to a database.
"""

from __future__ import annotations

import json
import re
import secrets
from pathlib import Path
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

from hr_agents.identity import ActorProvenance, ActorRef, ActorType
from hr_agents.rbac import RoleId

DEFAULT_APP_NAME = "HRAgents"
DEFAULT_TIMEZONE = "Asia/Jakarta"
DEFAULT_STORE_BACKEND = "postgres"
DEFAULT_LLM_MODEL = "test"


def generate_api_key() -> str:
    """A key strong enough to be the only credential on a fresh install."""
    return secrets.token_urlsafe(32)


def validate_timezone(name: str) -> str:
    """Return a valid IANA zone name; raise ValueError for anything else."""
    cleaned = name.strip()
    if not cleaned:
        raise ValueError("timezone must not be blank")
    try:
        ZoneInfo(cleaned)
    except ZoneInfoNotFoundError as exc:
        raise ValueError(f"unknown timezone: {cleaned}") from exc
    return cleaned


def actor_id_for(operator: str) -> str:
    """A stable, URL-safe actor id derived from the operator's display name."""
    slug = re.sub(r"[^a-z0-9]+", "-", operator.strip().lower()).strip("-")
    return slug or "admin"


def setup_actor(operator: str) -> ActorRef:
    """The operator as the authenticated HR admin setup content is filed under."""
    return ActorRef(
        actor_id=actor_id_for(operator),
        actor_type=ActorType.HUMAN,
        provenance=ActorProvenance.AUTHENTICATED,
        role=RoleId.HR_ADMIN.value,
    )


def render_env(
    *,
    operator: str,
    api_key: str,
    app_name: str = DEFAULT_APP_NAME,
    timezone: str = DEFAULT_TIMEZONE,
    store_backend: str = DEFAULT_STORE_BACKEND,
    llm_model: str = DEFAULT_LLM_MODEL,
) -> str:
    """The `.env` a fresh self-host install starts from.

    One role-bound admin principal, so the dashboard key is attributable on the
    audit chain and can be rotated by editing this file. The offline model is the
    default; a provider is an edit here, not a requirement to boot.
    """
    if not operator.strip():
        raise ValueError("operator must not be blank")
    if store_backend not in {"memory", "postgres"}:
        raise ValueError("store_backend must be 'memory' or 'postgres'")
    principals = json.dumps(
        [
            {
                "key": api_key,
                "role": "hr_admin",
                "actor_id": actor_id_for(operator),
            }
        ],
        separators=(",", ":"),
    )
    lines = [
        "# HRAgents local configuration, generated by scripts/setup.py.",
        "# Never commit this file; it holds the dashboard API key.",
        "",
        f"HRAGENTS_ACTOR_NAME={json.dumps(operator.strip())}",
        f"HRAGENTS_APP_NAME={json.dumps(app_name.strip() or DEFAULT_APP_NAME)}",
        f"HRAGENTS_TIMEZONE={validate_timezone(timezone)}",
        f"HRAGENTS_STORE_BACKEND={store_backend}",
        f"HRAGENTS_LLM_MODEL={json.dumps(llm_model.strip() or DEFAULT_LLM_MODEL)}",
        "",
        "# One role-bound principal. Paste the key into the dashboard sign-in.",
        f"HRAGENTS_API_PRINCIPALS='{principals}'",
        "",
    ]
    return "\n".join(lines)


def write_env(path: Path, content: str, *, force: bool = False) -> None:
    """Write the file atomically enough for a config file; never overwrite silently."""
    if path.exists() and not force:
        raise FileExistsError(f"{path} already exists; pass --force to replace it")
    path.write_text(content, encoding="utf-8", newline="\n")
